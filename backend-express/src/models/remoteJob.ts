// Sequelize model for the RemoteJobs table (columns must stay in sync with migration 08)
import type { Optional } from "sequelize";
import { Column, DataType, Model, PrimaryKey, Table } from "sequelize-typescript";

// A dataset waiting for, or being worked on by, the large-memory worker
export interface IRemoteJob {
    id: string;
    dataset_id: string;
    file_version: number;
    claimedAt: Date | null;
    heartbeatAt: Date | null;
    createdAt: Date;
    updatedAt: Date | null;
}

// Fields the database fills in are optional when a row is created
type RemoteJobCreation = Optional<IRemoteJob, "claimedAt" | "heartbeatAt" | "createdAt" | "updatedAt">;

// Maps this class to the "RemoteJobs" table and enables createdAt/updatedAt timestamps
@Table({
    tableName: "RemoteJobs",
    timestamps: true,
})
export class RemoteJobs extends Model<IRemoteJob, RemoteJobCreation> {
    // Primary key: UUID generated by the application
    @PrimaryKey
    @Column({
        type: DataType.UUID,
        allowNull: false,
    })
    declare id: string;

    // The dataset to process (unique: at most one job per dataset)
    @Column({
        type: DataType.UUID,
        allowNull: false,
        unique: true,
    })
    declare dataset_id: string;

    // Version of the RDS file the job was made for
    @Column({
        type: DataType.INTEGER,
        allowNull: false,
    })
    declare file_version: number;

    // When a worker claimed the job; null while it waits
    @Column({
        type: DataType.DATE,
        allowNull: true,
    })
    declare claimedAt: Date | null;

    // When the worker last reported in; a claim without a recent heartbeat is given up
    @Column({
        type: DataType.DATE,
        allowNull: true,
    })
    declare heartbeatAt: Date | null;

    // Row creation time
    @Column({
        type: DataType.DATE,
        allowNull: false,
    })
    declare createdAt: Date;

    // Time of the last change
    @Column({
        type: DataType.DATE,
        allowNull: true,
    })
    declare updatedAt: Date | null;
}

export default RemoteJobs;
